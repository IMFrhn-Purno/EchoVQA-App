class ClinicalTextEncoder(nn.Module):
    def __init__(self, bert_model):
        super(ClinicalTextEncoder, self).__init__()
        self.bert = bert_model

    def forward(self, input_ids, attention_mask):
        outputs = self.bert(input_ids=input_ids, attention_mask=attention_mask)
        return outputs.last_hidden_state[:, 0, :]

def build_video_encoder():
    model = r2plus1d_18(weights=None)
    model.fc = nn.Identity()
    return model

class FusionModule(nn.Module):
    def __init__(self, video_dim=512, text_dim=768, embed_dim=512, num_heads=8, num_layers=2, num_qtype_classes=3, num_view_classes=5):
        super(FusionModule, self).__init__()
        self.text_projection = nn.Linear(text_dim, embed_dim)
        self.video_projection = nn.Linear(video_dim, embed_dim)

        encoder_layer = nn.TransformerEncoderLayer(
            d_model=embed_dim,
            nhead=num_heads,
            dim_feedforward=2048,
            batch_first=True
        )
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.view_classifier = nn.Linear(embed_dim, num_view_classes)
        self.qtype_classifier = nn.Linear(embed_dim, num_qtype_classes)

    def forward(self, video_features, question_features, report_features, mask_report=False):
        v_proj = self.video_projection(video_features).unsqueeze(1)
        q_proj = self.text_projection(question_features).unsqueeze(1)

        if mask_report:
            r_feat = torch.zeros_like(report_features).to(report_features.device)
        else:
            r_feat = report_features

        r_proj = self.text_projection(r_feat).unsqueeze(1)
        combined_sequence = torch.cat([v_proj, q_proj, r_proj], dim=1)
        fused_seq = self.transformer(combined_sequence)
        fused_rep = fused_seq.mean(dim=1)

        view_logits = self.view_classifier(fused_rep)
        qtype_logits = self.qtype_classifier(fused_rep)

        return fused_rep, view_logits, qtype_logits

class EchoVQAHeads(nn.Module):
    def __init__(self, embed_dim=512):
        super(EchoVQAHeads, self).__init__()
        self.ordinal_head = nn.Sequential(
            nn.Linear(embed_dim, 256),
            nn.ReLU(),
            nn.Dropout(0.1),
            nn.Linear(256, 4)
        )
        self.binary_head = nn.Sequential(
            nn.Linear(embed_dim, 256),
            nn.ReLU(),
            nn.Linear(256, 1)
        )
        self.regression_head = nn.Sequential(
            nn.Linear(embed_dim, 256),
            nn.ReLU(),
            nn.Linear(256, 1)
        )

    def forward(self, fused_features):
        return {
            "ordinal": self.ordinal_head(fused_features),
            "binary": torch.sigmoid(self.binary_head(fused_features)),
            "regression": self.regression_head(fused_features)
        }

class EchocardiogramVQA(nn.Module):
    def __init__(self, video_encoder, text_encoder, fusion_module, output_heads):
        super(EchocardiogramVQA, self).__init__()
        self.video_encoder = video_encoder
        self.text_encoder = text_encoder
        self.fusion_module = fusion_module
        self.output_heads = output_heads

    def forward(self, video, q_ids, q_mask, r_ids, r_mask, mask_report=False):
        v_feat = self.video_encoder(video)
        q_feat = self.text_encoder(q_ids, q_mask)
        r_feat = self.text_encoder(r_ids, r_mask)

        fused_vector, view_logits, qtype_logits = self.fusion_module(
            v_feat, q_feat, r_feat, mask_report=mask_report
        )

        results = self.output_heads(fused_vector)
        results['view_logits'] = view_logits
        results['qtype_logits'] = qtype_logits

        return results

