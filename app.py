        with st.spinner("Running multimodal inference..."):
            video_tensor = preprocess_video(temp_video_path).unsqueeze(0).to(device)

            q_tokens = tokenizer(str(clinical_question), truncation=True, padding='max_length', max_length=128, return_tensors="pt")
            r_tokens = tokenizer(str(clinical_report), truncation=True, padding='max_length', max_length=128, return_tensors="pt")

