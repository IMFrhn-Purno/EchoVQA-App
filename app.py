@st.cache_resource
def initialise_system():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    tokenizer = AutoTokenizer.from_pretrained("emilyalsentzer/Bio_ClinicalBERT")
    clinical_bert = AutoModel.from_pretrained("emilyalsentzer/Bio_ClinicalBERT")
    text_encoder = ClinicalTextEncoder(clinical_bert).to(device)

    video_encoder = build_video_encoder().to(device)
    fusion_layer = FusionModule().to(device)
    output_heads = EchoVQAHeads(embed_dim=512).to(device)

    model = EchocardiogramVQA(
        video_encoder=video_encoder,
        text_encoder=text_encoder,
        fusion_module=fusion_layer,
        output_heads=output_heads
    ).to(device)

    checkpoint_path = "best_echovqa_model_fold1.pt"
    if os.path.exists(checkpoint_path):
        checkpoint = torch.load(checkpoint_path, map_location=device)
        state_dict = checkpoint['state_dict'] if isinstance(checkpoint, dict) and 'state_dict' in checkpoint else checkpoint

        cleaned_state_dict = {}
        for k, v in state_dict.items():
            new_key = k.replace('module.', '')
            if new_key.startswith('fusion_'):
                new_key = new_key.replace('fusion_', 'fusion_module.', 1)
            cleaned_state_dict[new_key] = v

        model.load_state_dict(cleaned_state_dict, strict=True)
    else:
        raise FileNotFoundError(
            f"Checkpoint not found: {checkpoint_path}"
        )

    model.eval()
    print("===============================")
    print("MODEL LOADED SUCCESSFULLY")
    print("===============================")

    total_params = sum(
        p.numel()
        for p in model.parameters()
    )

    print(f"Total parameters: {total_params:,}")
    return model, tokenizer, device

model, tokenizer, device = initialise_system()

